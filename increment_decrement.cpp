#include <iostream>
using namespace std;

int main() {
   int x=4;
   cout << x << "\n";
   x++;                   // post increment by 1
   cout << x << "\n";
   x--;                  // post  decrement by 1
   cout << x << "\n";
   ++x;                  // Pre increment by 1
   cout << x << "\n";
   --x;                  // Pre decrement by 1
   cout << x << "\n";

}